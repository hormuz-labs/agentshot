// Render the front-view full-body 3D mascot once, then derive every repository brand asset from it.
// npm run brand — uses the existing Electron + Three.js toolchain, no image downloads or model services.
import { _electron as electron } from 'playwright-core'
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { prepareElectron } from './run-electron.mjs'

const root = join(import.meta.dirname, '..')
const tmp = await mkdtemp(join(tmpdir(), 'agentshot-brand-'))
const executablePath = await prepareElectron()
const env = { ...process.env, MANUL_PROJECTS: join(tmp, 'projects') }
delete env.ELECTRON_RENDERER_URL
const bundle = await build({ entryPoints: [join(root, 'src/renderer/src/components/mascot/scene.ts')], bundle: true,
  write: false, format: 'iife', globalName: 'AgentShotBrand', alias: { '@': join(root, 'src/renderer/src') } })
const app = await electron.launch({ cwd: root, executablePath, args: ['.', `--user-data-dir=${join(tmp, 'ud')}`], env })
try {
  const win = await app.firstWindow()
  await win.goto('data:text/html,<html><body style="margin:0"><canvas id="portrait"></canvas></body></html>')
  await win.addScriptTag({ content: bundle.outputFiles[0].text })
  const data = await win.evaluate(() => {
    const scene = AgentShotBrand.createMascotScene(document.getElementById('portrait'))
    const png = scene.renderLogo(1024)
    scene.dispose()
    return png
  })
  const png = Buffer.from(data.split(',')[1], 'base64')
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 1024 1024" role="img" aria-label="Manul, a full-body Pallas’s cat"><title>Manul</title><image width="1024" height="1024" xlink:href="${data}"/></svg>\n`
  await mkdir(join(root, 'build/icons'), { recursive: true })
  await mkdir(join(tmp, 'brand.iconset'))
  await Promise.all([
    writeFile(join(root, 'build/icon.png'), png),
    writeFile(join(root, 'build/icon.svg'), svg),
    writeFile(join(root, 'src/renderer/public/manul.png'), png),
    writeFile(join(root, 'src/renderer/public/manul.svg'), svg),
  ])
  for (const size of [16, 32, 48, 64, 128, 256, 512, 1024]) {
    const image = await app.evaluate(({ nativeImage }, { data, size }) =>
      nativeImage.createFromDataURL(data).resize({ width: size, height: size, quality: 'best' }).toPNG().toString('base64'), { data, size })
    await writeFile(join(root, `build/icons/${size}x${size}.png`), Buffer.from(image, 'base64'))
    if ([16, 32, 128, 256, 512].includes(size)) {
      await writeFile(join(tmp, `brand.iconset/icon_${size}x${size}.png`), Buffer.from(image, 'base64'))
    }
    if ([32, 64, 256, 512, 1024].includes(size)) {
      await writeFile(join(tmp, `brand.iconset/icon_${size / 2}x${size / 2}@2x.png`), Buffer.from(image, 'base64'))
    }
  }
  execFileSync('node', ['scripts/ico.mjs', 'build/icon.ico', ...[256, 128, 64, 48, 32, 16].map(s => `build/icons/${s}x${s}.png`)], { cwd: root })
  if (process.platform === 'darwin') execFileSync('iconutil', ['-c', 'icns', join(tmp, 'brand.iconset'), '-o', join(root, 'build/icon.icns')])
  // Account return pages display the logo at 128px; use a crisp 2× copy rather than embedding the 1024px master.
  const pageImage = await app.evaluate(({ nativeImage }, data) =>
    nativeImage.createFromDataURL(data).resize({ width: 256, height: 256, quality: 'best' }).toPNG().toString('base64'), data)
  const chunks = pageImage.match(/.{1,512}/g).map(chunk => `  '${chunk}'`).join(' +\n')
  await writeFile(join(root, 'src/shared/brand.ts'), `// Generated by npm run brand from the front-view full-body 3D mascot.\nexport const AGENTSHOT_LOGO = 'data:image/png;base64,' +\n${chunks}\n`)
  console.log('Full-body AgentShot branding generated: renderer, account service, PNG sizes, SVG, ICO and macOS ICNS.')
} finally {
  await app.close()
  await rm(tmp, { recursive: true, force: true })
}
